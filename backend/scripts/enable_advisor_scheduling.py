"""Persist advisor hours and blocked dates; enable IDs for new bookings."""
from contextlib import closing
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from db import get_db_connection


def migrate():
    with closing(get_db_connection()) as connection:
        with connection:
            with connection.cursor() as cursor:
                cursor.execute("SET LOCAL lock_timeout = '10s'")
                cursor.execute('''CREATE TABLE IF NOT EXISTS advisor_schedule (
                    advisor_id BIGINT PRIMARY KEY REFERENCES app_user(user_id) ON DELETE CASCADE,
                    availability JSONB NOT NULL,
                    blocked_dates JSONB NOT NULL DEFAULT '[]'::jsonb,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )''')
                cursor.execute('ALTER TABLE advisor_schedule ENABLE ROW LEVEL SECURITY')
                cursor.execute('''ALTER TABLE advisor_schedule ADD COLUMN IF NOT EXISTS slot_minutes
                    INTEGER NOT NULL DEFAULT 30 CHECK (slot_minutes IN (15, 30, 45, 60, 90, 120))''')
                # Snapshot duration on each booking so later schedule edits preserve its length.
                cursor.execute('''ALTER TABLE appointment ADD COLUMN IF NOT EXISTS duration_minutes
                    INTEGER NOT NULL DEFAULT 30 CHECK (duration_minutes IN (15, 30, 45, 60, 90, 120))''')
                # Existing installations may use manually assigned appointment IDs.
                cursor.execute('''DO $$ DECLARE next_id BIGINT; BEGIN
                    IF EXISTS (SELECT 1 FROM information_schema.columns
                        WHERE table_schema = current_schema() AND table_name = 'appointment'
                        AND column_name = 'appointment_id' AND is_identity = 'NO' AND column_default IS NULL) THEN
                        LOCK TABLE appointment IN ACCESS EXCLUSIVE MODE;
                        SELECT COALESCE(MAX(appointment_id), 0) + 1 INTO next_id FROM appointment;
                        EXECUTE format('ALTER TABLE appointment ALTER COLUMN appointment_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next_id);
                    END IF;
                END $$''')
    print('Advisor scheduling enabled. Existing appointments were preserved.')


if __name__ == '__main__':
    migrate()
